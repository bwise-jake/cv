/**
 * Pure helpers for the Atlassian theme's ADS tokens. src/styles/atlassian.css writes every token as
 * `var(--ds-name, fallback)`; `adsTokensCss()` reads the light-theme value of each one from
 * @atlaskit/tokens and builds src/styles/ads-tokens.css so the page defines them. The same data lets
 * tests/ads-tokens.test.ts check that every fallback is the real value.
 */
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

/**
 * The light-theme value and CSS custom property of every ADS token, keyed by dotted token name.
 * @atlaskit/tokens has no `exports` field, so a native ESM import of these sub-directories fails
 * (ERR_UNSUPPORTED_DIR_IMPORT); require() resolves them through their package.json.
 */
export function tokenData(): { defaults: Record<string, string>; names: Record<string, string> } {
  const defaults = require('@atlaskit/tokens/token-default-values') as { default: Record<string, string> };
  const names = require('@atlaskit/tokens/token-names') as { default: Record<string, string> };
  return { defaults: defaults.default, names: names.default };
}

const TOKEN_CALL = /var\(\s*(--ds-[a-z0-9]+(?:-[a-z0-9]+)*)\s*,/g;

/** Maps each `--ds-*` custom property used as `var(--ds-name, fallback)` to its fallback text. */
export function usedTokens(css: string): Map<string, string> {
  const used = new Map<string, string>();
  for (const match of css.matchAll(TOKEN_CALL)) {
    const start = match.index + match[0].length;
    let depth = 1;
    let end = start;
    while (end < css.length && depth > 0) {
      if (css[end] === '(') depth += 1;
      else if (css[end] === ')') depth -= 1;
      end += 1;
    }
    used.set(match[1], css.slice(start, end - 1).trim());
  }
  return used;
}

/**
 * Font family, size and heading-weight tokens stay fallback-only: ADS's own values (Atlassian Sans,
 * weight 653) would replace the Inter/Outfit stand-ins and change every PDF's line breaks.
 */
export function isFallbackOnly(key: string): boolean {
  return key.startsWith('font.') && !key.startsWith('font.weight.');
}

/** The generated stylesheet that defines the ADS tokens atlassian.css uses, for the Atlassian theme only. */
export function adsTokensCss(atlassianCss: string): string {
  const { defaults, names } = tokenData();
  const keyByProperty = new Map(Object.entries(names).map(([key, property]) => [property, key]));
  const lines: string[] = [];
  for (const property of [...usedTokens(atlassianCss).keys()].sort()) {
    const key = keyByProperty.get(property);
    const value = key === undefined ? undefined : defaults[key];
    if (key === undefined || value === undefined) throw new Error(`Unknown ADS token ${property}`);
    if (isFallbackOnly(key)) continue;
    lines.push(`  ${property}: ${value};`);
  }
  return [
    '/* Generated by `npm run ads:tokens` from @atlaskit/tokens (light theme). Do not edit.',
    '   Defines the ADS tokens src/styles/atlassian.css uses, for the Atlassian theme only. Font',
    "   tokens are left out on purpose: ADS's own families would replace the Inter/Outfit stand-ins. */",
    ':root[data-theme="atlassian"] {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

function normalise(value: string): string {
  const collapsed = value.trim().replace(/\s+/g, ' ').toLowerCase();
  return /^0(rem|px)?$/.test(collapsed) ? '0' : collapsed;
}

/** Case-insensitive, whitespace-collapsed comparison that treats `0`, `0rem` and `0px` as equal. */
export function sameValue(a: string, b: string): boolean {
  return normalise(a) === normalise(b);
}
